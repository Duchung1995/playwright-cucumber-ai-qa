#!/usr/bin/env node
// PreToolUse(Edit|Write|MultiEdit): protects files agents must not change on their own.
// - .env / lockfile / generated reports: denied.
// - rubrics: the evaluation contract; agents being judged may not rewrite it, so a human must approve.
import { readFileSync } from 'node:fs';

const input = JSON.parse(readFileSync(0, 'utf8'));
const file = input.tool_input?.file_path ?? '';
const rel = file.replace(`${process.env.CLAUDE_PROJECT_DIR ?? process.cwd()}/`, '');

const decide = (permissionDecision, reason) =>
  console.log(
    JSON.stringify({
      hookSpecificOutput: {
        hookEventName: 'PreToolUse',
        permissionDecision,
        permissionDecisionReason: reason,
      },
    }),
  );

if (/^\.env(\..+)?$/.test(rel) && rel !== '.env.example') {
  decide('deny', '.env holds local secrets; edit .env.example and let the user copy values.');
} else if (rel === 'package-lock.json') {
  decide('deny', 'Change dependencies with npm install, never by editing the lockfile.');
} else if (rel.startsWith('reports/')) {
  decide('deny', 'reports/ is generated by test runs and is evidence for triage; do not edit it.');
} else if (rel.startsWith('.claude/rubrics/')) {
  decide('ask', 'Rubrics are the quality contract used to judge agent output. A human must approve changes.');
}
